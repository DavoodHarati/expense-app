'use strict';
const assert = require('node:assert/strict'), fs = require('node:fs'), vm = require('node:vm');
const src = fs.readFileSync('app.js', 'utf8');
const code = src.slice(src.indexOf('function featureOn(name)'), src.indexOf('let welcomeDismissed'));
let value = {};
const ctx = vm.createContext({ load: () => value }); vm.runInContext(code, ctx);
for (const key of ['assistant','invoice','loan','reminder','budget','sms','vehicle']) assert.equal(ctx.featureOn(key), true);
value = { invoice: false, assistant: true }; assert.equal(ctx.featureOn('invoice'), false); assert.equal(ctx.featureOn('assistant'), true);
value.invoice = true; assert.equal(ctx.featureOn('invoice'), true);
value = null; assert.equal(ctx.featureOn('invoice'), true);
assert.match(src, /'features', 'dataOwner'/);
assert.ok(src.includes("if (!('dataOwner' in data)) data.dataOwner = ''"));
assert.ok(src.includes('preserveBiz: keep, customer: keep ? original.customer'));
assert.ok(src.includes("if (featureOn('invoice')) { tt.customer"));
assert.match(src, /id="features-settings"/);
assert.match(src, /data-feature-section/);
const backupCode = src.slice(src.indexOf('const BACKUP_KEYS'), src.indexOf('let tx ='));
const b = vm.createContext({}); vm.runInContext(backupCode, b);
const old = { format: 'expense-app-backup', version: 1, data: { tx:'[]', accounts:'{}' } };
assert.ok(b.validateFullBackup(old));
assert.ok(b.validateFullBackup({ ...old, data: { ...old.data, features:'{"invoice":false}', dataOwner:'' } }));
assert.throws(() => b.validateFullBackup({ ...old, data: { ...old.data, features:'{"invoice":"false"}' } }));
