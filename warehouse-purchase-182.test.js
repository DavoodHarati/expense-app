const fs = require('fs'), vm = require('vm'), assert = require('assert');
const source = fs.readFileSync('warehouse.js', 'utf8');
const memory = new Map();
const localStorage = {getItem:k=>memory.has(k)?memory.get(k):null,setItem:(k,v)=>memory.set(k,String(v)),removeItem:k=>memory.delete(k)};
const env = {localStorage, document:{addEventListener(){},getElementById(){return null}}, Date, Math, console};
env.window = env;
vm.runInNewContext(source, env);
const product={id:'i1',name:'کالا',buy:10,sell:20};
const empty={groups:[],items:[product],moves:[]};
const purchase={id:'f1',kind:'خرید اجناس انبار',date:'1405/08/01',lines:[{warehouseItem:'i1',quantity:5,price:12}]};
let plan=env.warehousePlanPurchase182(purchase,empty);
assert.strictEqual(plan.moves.length,1);
assert.strictEqual(plan.moves[0].qty,5);
assert.strictEqual(plan.moves[0].price,12);
plan=env.warehousePlanPurchase182(purchase,plan);
assert.strictEqual(plan.moves.length,1,'editing does not duplicate');
plan=env.warehousePlanPurchase182({...purchase,lines:[{...purchase.lines[0],quantity:7}]},plan);
assert.strictEqual(plan.moves[0].qty,7);
const noMove=env.warehousePlanPurchase182({...purchase,proforma:true},empty);
assert.strictEqual(noMove.moves.length,0);
const consumed=env.warehousePlanPurchase182({id:'f2',kind:'خدمات',date:purchase.date,wh:[{item:'i1',qty:3,buy:12,price:20}]},plan);
assert.strictEqual(consumed.moves.reduce((s,x)=>s+x.qty,0),4);
assert.throws(()=>env.warehousePlanPurchase182({...purchase,lines:[{...purchase.lines[0],quantity:2}]},consumed),/موجودی/);
assert.throws(()=>env.warehousePlanPurchase182({...purchase,lines:[{...purchase.lines[0],warehouseItem:''}]},empty),/انبار/);
assert.strictEqual(empty.moves.length,0,'planning does not mutate input');
const app=fs.readFileSync('app.js','utf8'), index=fs.readFileSync('index.html','utf8'), invoice=fs.readFileSync('invoice.js','utf8');
assert(app.includes("'wh', 'showSales182'"));
assert(index.includes('warehouse.js?v=182'));
assert(invoice.includes("kind === 'خرید اجناس انبار'"));
console.log('warehouse purchase, editing, proforma, stock and backup: PASS');
